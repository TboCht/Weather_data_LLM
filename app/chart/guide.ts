export const chartGuide = `When a Weather response is in hand, pick a chart. Write the question it answers, then choose the type that answers that question.

- Line: change over time. Not for unordered categories.
- Area: a trend where the filled region shows amount. Not when the areas cover each other.
- Bar: compare items. Horizontal bars when labels are long.
- Donut: two or three parts of one whole.
- Bubble: three numbers per point. Not when the marks pile up.
- Radar: one or two shapes across a handful of measures.
- Radial bar: compare a few magnitudes as arcs.
- Funnel: stages of one amount.
- Candlestick: open, high, low, and close across days.
- Status tracker: a status at each time.
- Sankey: how an amount moves from one thing to another.
- Map: where the places are.

Choose colors with purpose. Temperature is red. Precipitation is blue. Give any other variable a color that matches what it measures. When several series are the same kind of data, use shades distinct enough to tell apart.

An axis starts at 0 when the values reach 0 or sit close to it. When they do not, the axis starts near the data, so a small change stays visible.`
