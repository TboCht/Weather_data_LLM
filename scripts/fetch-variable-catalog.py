"""Pull variable codes and their one-line descriptions from the Open-Meteo docs.

The catalog is generated source. Re-run this script when those docs change.
It does not run during `nuxt build`, so tests stay offline.
"""

import html
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "server" / "weather" / "variable-catalog.ts"

PAGES = {
    "forecast": "https://open-meteo.com/en/docs",
    "archive": "https://open-meteo.com/en/docs/historical-weather-api",
    "historicalForecast": "https://open-meteo.com/en/docs/historical-forecast-api",
    "previousRuns": "https://open-meteo.com/en/docs/previous-runs-api",
    "singleRuns": "https://open-meteo.com/en/docs/single-runs-api",
    "ensemble": "https://open-meteo.com/en/docs/ensemble-api",
    "marine": "https://open-meteo.com/en/docs/marine-weather-api",
    "airQuality": "https://open-meteo.com/en/docs/air-quality-api",
    "flood": "https://open-meteo.com/en/docs/flood-api",
    "climate": "https://open-meteo.com/en/docs/climate-api",
    "seasonal": "https://open-meteo.com/en/docs/seasonal-forecast-api",
    "satelliteRadiation": "https://open-meteo.com/en/docs/satellite-radiation-api",
}

# Sections each source documents as request parameters. 15-minute groups are
# shown on some pages but are not parameters of these tools.
SECTIONS = {
    "forecast": ("current", "hourly", "daily"),
    "archive": ("hourly", "daily"),
    "historicalForecast": ("current", "hourly", "daily"),
    "previousRuns": ("current", "hourly", "daily"),
    "singleRuns": ("current", "hourly", "daily"),
    "ensemble": ("hourly",),
    "marine": ("current", "hourly", "daily"),
    "airQuality": ("current", "hourly"),
    "flood": ("daily",),
    "climate": ("daily",),
    "seasonal": ("hourly", "daily"),
    "satelliteRadiation": ("hourly", "daily"),
}

CHECKBOX = re.compile(
    r'title="([^"]+)"[\s\S]{0,900}?id="([a-z0-9_]+)_(hourly|daily|current)" role="checkbox"'
)
PREVIOUS_DAY = re.compile(
    r'id="([a-z0-9_]+)_hourly_previous_day([1-7])" role="checkbox"'
)


def clean(text: str) -> str:
    text = html.unescape(text)
    text = re.sub(r"<[^>]+>", "", text)
    return " ".join(text.split())


def fetch(url: str) -> str:
    return subprocess.check_output(
        ["curl", "-fsSL", "-A", "Mozilla/5.0", url],
        text=True,
    )


def parse_page(page: str) -> dict[str, dict[str, str]]:
    found: dict[str, dict[str, str]] = {}
    for title, code, section in CHECKBOX.findall(page):
        found.setdefault(section, {})
        found[section].setdefault(code, clean(title))
    return found


def listings(codes: dict[str, str]) -> list[dict[str, str]]:
    return [
        {"code": code, "description": description}
        for code, description in sorted(codes.items())
    ]


def main() -> None:
    pages = {key: fetch(url) for key, url in PAGES.items()}
    parsed = {key: parse_page(page) for key, page in pages.items()}

    # Historical forecast and single runs are the forecast API. Copy current
    # codes when that page does not render a current group.
    for key in ("historicalForecast", "singleRuns"):
        parsed[key].setdefault("current", dict(parsed["forecast"].get("current", {})))

    previous = {section: dict(codes) for section, codes in parsed["forecast"].items()}
    hourly_base = previous.setdefault("hourly", {})
    for base, day in PREVIOUS_DAY.findall(pages["previousRuns"]):
        description = hourly_base.get(base, base.replace("_", " "))
        unit = "day" if day == "1" else "days"
        hourly_base[f"{base}_previous_day{day}"] = (
            f"{description}, predicted {day} {unit} before valid time"
        )
    parsed["previousRuns"] = previous

    catalog: dict[str, dict[str, list[dict[str, str]]]] = {}
    for source, sections in SECTIONS.items():
        catalog[source] = {}
        for section in sections:
            codes = parsed[source].get(section, {})
            if not codes:
                raise SystemExit(f"{source} {section} has no codes")
            catalog[source][section] = listings(codes)

    body = json.dumps(catalog, indent=2, ensure_ascii=False)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/fetch-variable-catalog.py from the Open-Meteo docs.\n"
        "// Re-run that script to refresh the codes. Do not edit the listings by hand.\n\n"
        "export interface VariableListing {\n"
        "  code: string\n"
        "  description: string\n"
        "}\n\n"
        "export type VariableSectionName = 'current' | 'hourly' | 'daily'\n\n"
        "export const variableCatalog: Record<\n"
        "  string,\n"
        "  Partial<Record<VariableSectionName, VariableListing[]>>\n"
        f"> = {body}\n",
        encoding="utf-8",
    )
    for source, sections in catalog.items():
        counts = {name: len(codes) for name, codes in sections.items()}
        print(f"{source}: {counts}")


if __name__ == "__main__":
    main()
